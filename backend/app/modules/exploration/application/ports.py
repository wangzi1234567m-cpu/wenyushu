from datetime import datetime
from typing import Protocol
from uuid import UUID


class ExplorationRepository(Protocol):
    def owned_version(self, actor_id: UUID, version_id: UUID) -> bool: ...
    def create(self, actor_id: UUID, version: dict, now: datetime) -> dict: ...
    def get(self, actor_id: UUID, exploration_id: UUID, now: datetime) -> dict: ...
    def submit(
        self, actor_id: UUID, exploration_id: UUID, answer: dict, version: dict, now: datetime
    ) -> dict: ...
    def link_intent(self, actor_id: UUID, exploration_id: UUID, intent_id: UUID) -> None: ...
