from datetime import datetime
from typing import Protocol, Self
from uuid import UUID

from app.modules.identity.domain.actor import Actor


class ActorRepository(Protocol):
    def find(self, token_hash: str) -> Actor | None: ...
    def add(self, actor: Actor) -> None: ...
    def revoke(self, actor_id: UUID, now: datetime) -> None: ...


class IdentityUnitOfWork(Protocol):
    actors: ActorRepository

    def __enter__(self) -> Self: ...
    def __exit__(self, *args: object) -> None: ...
    def commit(self) -> None: ...


class ActorResolver(Protocol):
    def resolve(self, credential: str | None) -> Actor: ...


class AuthorizationPort(Protocol):
    def require_owner(self, actor: Actor, owner_id: UUID | None) -> None: ...


class CsrfPort(Protocol):
    def issue(self, credential: str, now: datetime) -> str: ...
    def verify(self, token: str | None, credential: str, now: datetime) -> bool: ...
